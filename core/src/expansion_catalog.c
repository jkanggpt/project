const ExpansionBuildingSpec *expansion_spec(int type) {
    return type >= 0 && type < CORE_BLD_COUNT ? &SPECS[type] : NULL;
}
static void fill_definitions_from(Defs *defs, int expanded, int first) {
    if (expanded) expansion_raider_definitions(defs);
    int type;
    for (type = first; type < CORE_BLD_COUNT; type++) {
        const ExpansionBuildingSpec *s = &SPECS[type];
        BuildingDef *d = &defs->buildings[type];
        memset(d, 0, sizeof(*d));
        strcpy(d->key, s->key);
        d->w = s->w;
        d->h = s->h;
        memcpy(d->cost, s->cost, sizeof(d->cost));
        d->build_ticks = s->hours * 6;
        d->max_hp = s->hp;
        d->worker_slots = s->workers;
        d->resident_slots = s->residents;
        d->produces = -1;
        d->secondary = -1;
        d->work_radius = s->radius;
        d->ideal_terrain = 1;
        d->required_rank = expanded ? s->rank : 5;
        d->category = s->category;
        d->line = (s->flags & (CORE_EXP_ROAD | CORE_EXP_WALL | CORE_EXP_GATE)) != 0;
        d->attack = s->attack;
        d->attack_range = s->range;
        d->attack_cooldown = s->cooldown;
        d->wage = (int[]){1, 1, 2, 2, 3, 4}[s->rank];
        if (type == CORE_BLD_KEEP)
            d->storage = 300;
        if (s->flags & (CORE_EXP_WALL | CORE_EXP_GATE))
            d->defense = 0;
        else if (type == CORE_BLD_BARRACKS)
            d->defense = 2;
        else if (s->attack)
            d->defense = s->rank + 1;
    }
}
void expansion_fill_definitions(Defs *defs, int expanded) {
    fill_definitions_from(defs, expanded, expanded ? 0 : CORE_LEGACY_BLD_COUNT);
}
void expansion_fill_new_definitions(Defs *defs) { fill_definitions_from(defs, 0, 66); }
